"""
bng_subscriber_agent.py — persistent per-subscriber session + attack-
traffic control daemon, run on `suscriptor` (Broadband domain,
distributed VM lab). This project's real BNG-side telemetry comes from FreeRADIUS's own accounting
records on `bng` itself (telemetry/broadband_adapter.py tails those
over SSH) -- this daemon's only job is making real IPoE-backed
subscriber sessions exist against accel-ppp and driving real attack
traffic sourced from each subscriber's own DHCP-assigned IP.

A "subscriber session" here is one macvlan sub-interface (roles/
suscriptor's setup_macvlans.sh.j2 creates macvlan1..N at boot, each
with its own MAC) running its own `dhclient` -- accel-ppp's ipoe module
on `bng` sees each as a distinct client (by Calling-Station-Id = MAC),
authenticates+accounts it via FreeRADIUS, and hands back a real IPv4
lease. `dhclient -r` (release) on stop sends a real DHCPRELEASE, which
is what makes FreeRADIUS emit a real Accounting-Stop record for that
session -- a genuine BNG-native session teardown, not a synthetic one.

This project also went through a PPPoE/pppd phase in between: an
earlier IPoE test showed accel-ppp's own ipoeN session interfaces never
counting real attack traffic under load (RX stuck at exactly 0 no
matter how much traffic flowed), which looked like a kernel ipoe.ko
classification bug, so the whole stack was rebuilt around PPPoE
instead. It wasn't the kernel driver. Confirmed on a later real run:
`suscriptor` is dual-homed (a management NIC besides the access-side
one each macvlanN rides on), and with no explicit routing override the
kernel's normal destination-based route lookup sent subscriber-sourced
attack traffic out the OTHER NIC entirely -- it never reached `bng`'s
access interface at all, so accel-ppp's ipoe.ko never got a chance to
see it. Subscriber._add_source_route() below is that override: a
per-subscriber `ip rule`/`ip route`, forcing traffic sourced from each
subscriber's own IP out its own macvlanN interface via `bng`'s real
gateway. Once in place, a real flood correctly moved a session's ipoeN
RX counters by ~200k packets in 8 seconds -- accel-ppp's accounting was
fine all along, and PPPoE's extra complexity (pppd, PAP, Van Jacobson
compression workarounds) turned out to be unnecessary. IPoE is simpler
for this project's actual point (real accounting telemetry): a
DHCP-leased macvlan interface is just an ordinary Ethernet-type
netdevice, no PPP-specific quirks to work around.

TCP_SYN/UDP attack traffic is generated by simulation/bng_flood.py
(spawned as a subprocess), NOT hping3 -- confirmed on a real run that
hping3 cannot reliably deliver traffic here at all: with no explicit
interface bind it picks the wrong NIC entirely (ignoring the very `ip
rule` this module sets up), and even with an explicit interface bind it
silently fails to actually reach the destination (this was tested both
over a PPP interface, where hping3's raw injection assumes Ethernet
framing PPP doesn't have, and over a plain macvlan/Ethernet interface,
where it still failed, apparently never resolving ARP correctly). See
bng_flood.py's own module docstring for the full diagnosis. ICMP still
shells out to the system `ping` binary, which already worked correctly
throughout this project's debugging (it's genuine kernel-stack traffic,
not a raw L2 injection).

Same tiny plain-text FIFO protocol as its predecessor (one command per
line): "baseline", "attack <scenario>", "stop", "stop_all" -- driven
over SSH by the former lab tooling BngLifecycle in distributed mode
(_ssh_write_fifo), unchanged on that end. One new command since:
"kick <ip>", sent by telemetry/broadband_adapter.py's own
apply_mitigation() right after a real unblock -- see
Subscriber.force_refresh()'s own docstring for why.

Also serves a tiny read-only HTTP endpoint (_StateHTTPHandler below,
GET /active_scenario on _HTTP_PORT) -- telemetry/broadband_adapter.py's
distributed-mode collect() polls this every cycle instead of SSHing in
a `cat` of _STATE_PATH, since that file changes only on attack start/
stop and a fresh SSH connection per poll (confirmed ~0.5s of handshake
alone) was pure overhead for reading the same unchanged bytes almost
every time.

A background thread (see run()/_resync_loop) periodically re-checks
every subscriber's real interface IP against what this daemon has
cached and re-syncs routing/the running attack process/the state file
if it changed -- confirmed on a real run that accel-ppp's IPoE pool
allocation does NOT reliably keep handing the same MAC the same IP
across successive DHCP transactions, repeatedly reassigning a LIVE
subscriber's address independent of dhclient's own lease-renewal timer.
Without this, self.ip goes silently stale and the attack process keeps
binding to an address no longer assigned to any local interface,
generating zero real traffic with no visible error anywhere -- see
Subscriber.resync_ip()'s own docstring for the full story.

Usage (on suscriptor, as root -- dhclient/ping/raw sockets need it):
  sudo python3 simulation/bng_subscriber_agent.py \\
      --target-ip 10.10.0.100 --gateway-ip 10.20.0.1 \\
      --parent-interface ens192 --fifo /run/bng-agent/cmd
"""

import argparse
import json
import os
import re
import subprocess
import sys
import threading
import time
